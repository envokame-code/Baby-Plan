/* يجمع ملفات JavaScript في ملف واحد js/bundle.js لتقليل عدد الطلبات عند أول فتح.
 * Concatenates the source files (in load order) into js/bundle.js. No dependencies.
 * Run after editing any file in js/:   node tools/build.js
 * The tests fail if bundle.js is out of date, so a stale bundle cannot be deployed. */
'use strict';
var fs = require('fs');
var path = require('path');
var ROOT = path.join(__dirname, '..');
var FILES = ['js/data/sources.js', 'js/data/growth.js', 'js/data/milestones.js', 'js/data/vaccines.js', 'js/data/content.js',
  'js/data/extra.js', 'js/data/topics.js', 'js/engine.js', 'js/store.js', 'js/app.js'];
function bundle() {
  return '/* ملف مُولَّد تلقائيًا — لا تعدّليه مباشرة. Generated by tools/build.js from: ' + FILES.join(', ') + ' */\n' +
    FILES.map(function (f) { return ';/* ' + f + ' */\n' + fs.readFileSync(path.join(ROOT, f), 'utf8'); }).join('\n');
}
module.exports = { bundle: bundle, FILES: FILES };
if (require.main === module) {
  fs.writeFileSync(path.join(ROOT, 'js/bundle.js'), bundle());
  console.log('js/bundle.js written');
}
